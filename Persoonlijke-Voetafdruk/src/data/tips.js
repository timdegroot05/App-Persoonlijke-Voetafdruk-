function makeFactTitle(text, categoryLabel) {
  const cleanedText = String(text).replace(/\.$/, "")
  const words = cleanedText.split(" ").slice(0, 5).join(" ")
  return `${categoryLabel}: ${words}`
}

function makeItems(type) {
  return categoryContent.flatMap((category) =>
    category[type].map((entry) => {
      const [title, body] = Array.isArray(entry)
        ? entry
        : [makeFactTitle(entry, category.label), entry]

      return {
        title,
        body,
        category: category.id,
        categoryLabel: category.label,
      }
    })
  )
}

export const tipCategories = categoryContent.map(({ id, label }) => ({ id, label }))
export const tipsList = makeItems("tips")
export const factsList = makeItems("facts")
export const allTipCards = [
  ...tipsList.map((tip) => ({ ...tip, type: "Tip" })),
  ...factsList.map((fact) => ({ ...fact, type: "Feitje" })),
]
